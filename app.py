"""
AI-Generated Text Detector — Streamlit App
Run with: streamlit run app.py

Folder structure expected:
    app.py
    models/
        baseline_model.pkl
        tfidf_vectorizer.pkl
"""

import streamlit as st
import pickle
import os
import pandas as pd

# ---------- PAGE CONFIG ----------
st.set_page_config(
    page_title="AI Text Detector",
    page_icon="🕵️",
    layout="centered"
)

# ---------- LOAD MODEL (cached so it only loads once) ----------
@st.cache_resource
def load_model():
    model_path = "models/baseline_model.pkl"
    vectorizer_path = "models/tfidf_vectorizer.pkl"

    if not os.path.exists(model_path) or not os.path.exists(vectorizer_path):
        st.error(
            f"Model files not found. Expected `{model_path}` and `{vectorizer_path}`. "
            "Make sure the `models/` folder is in the same directory as app.py."
        )
        st.stop()

    model = pickle.load(open(model_path, "rb"))
    vectorizer = pickle.load(open(vectorizer_path, "rb"))
    return model, vectorizer

model, vectorizer = load_model()

# ---------- PREDICTION FUNCTION ----------
def predict(text):
    X = vectorizer.transform([text])
    pred = model.predict(X)[0]

    confidence = None
    if hasattr(model, "predict_proba"):
        proba = model.predict_proba(X)[0]
        confidence = dict(zip(model.classes_, proba))

    return pred, confidence

# ---------- HEADER ----------
st.title("🕵️ AI-Generated Text Detector")
st.caption("IT41033 — NIA Mini Project | TF-IDF + Logistic Regression")

st.markdown(
    "Paste any text below to check whether it's likely **human-written** or **AI-generated**. "
    "This tool also shows the model's confidence — useful for understanding *how sure* the "
    "detector is, not just its final verdict."
)

# ---------- INPUT ----------
text_input = st.text_area(
    "Enter text to analyze:",
    height=200,
    placeholder="Paste an essay, article, or any paragraph here..."
)

col1, col2 = st.columns([1, 4])
with col1:
    analyze_btn = st.button("🔍 Analyze", type="primary", use_container_width=True)
with col2:
    if text_input:
        st.caption(f"{len(text_input.split())} words | {len(text_input)} characters")

# ---------- RESULT ----------
if analyze_btn:
    if not text_input.strip():
        st.warning("Please enter some text first.")
    else:
        with st.spinner("Analyzing..."):
            prediction, confidence = predict(text_input)

        st.divider()

        if prediction == "ai":
            st.error("### 🤖 Likely AI-Generated")
        else:
            st.success("### 🧑 Likely Human-Written")

        if confidence:
            st.subheader("Confidence Breakdown")
            conf_df = pd.DataFrame({
                "Class": [c.upper() for c in confidence.keys()],
                "Confidence": [v for v in confidence.values()]
            })
            st.bar_chart(conf_df.set_index("Class"))

            for cls, prob in confidence.items():
                st.write(f"**{cls.upper()}**: {prob*100:.1f}%")

        with st.expander("⚠️ Interpretation notes"):
            st.markdown(
                "- This model is a classical ML baseline (TF-IDF + Logistic Regression/Naive Bayes), "
                "not a deep learning detector — treat results as indicative, not definitive.\n"
                "- Formal, technical, or non-native-English writing may be more likely to be "
                "misclassified as AI-generated (a known limitation explored in this project).\n"
                "- Detection accuracy may be lower for text generated by AI models not seen "
                "during training, or for paraphrased AI text."
            )

# ---------- SIDEBAR: BATCH TESTING ----------
with st.sidebar:
    st.header("📄 Batch Test (optional)")
    st.caption("Upload a CSV with a `text` column to test multiple samples at once.")

    uploaded_file = st.file_uploader("Upload CSV", type=["csv"])

    if uploaded_file is not None:
        df = pd.read_csv(uploaded_file)

        if "text" not in df.columns:
            st.error("CSV must have a column named `text`.")
        else:
            if st.button("Run batch prediction"):
                with st.spinner("Predicting..."):
                    X = vectorizer.transform(df["text"].astype(str))
                    df["predicted"] = model.predict(X)

                st.success(f"Done — {len(df)} rows processed.")
                st.dataframe(df[["text", "predicted"]].head(20))

                csv_out = df.to_csv(index=False).encode("utf-8")
                st.download_button(
                    "⬇️ Download results as CSV",
                    csv_out,
                    "predictions.csv",
                    "text/csv"
                )

    st.divider()
    st.caption("Built for IT41033 — NIA Mini Project")